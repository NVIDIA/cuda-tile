// -gen-hint-key-impl
// ---------------------------------------------------------------------------

/// Per-architecture range override for a hint key.
/// Narrows the valid range for specific GPU architecture families.
struct ArchOverrideInfo {
  std::vector<std::string> families; // e.g. ["Ampere", "Ada"]
  int64_t min;
  int64_t max;
};

/// Complete metadata for one hint key, extracted from CudaTileHintKeyCase.
/// Used by -gen-hint-key-impl to generate validators and op-to-key mapping.
struct HintKeyInfo {
  std::string sym;       // C++ enum name and accessor suffix (e.g. "Latency")
  std::string str;       // MLIR string representation (e.g. "latency")
  std::string retType;   // Return type (e.g. "int", "bool")
  std::string validKind; // Validation strategy: "int_range", "pow2_range",
                         // "bool", or "string"
  int64_t validMin = 0;
  int64_t validMax = 0;
  std::vector<std::string> validForOps; // Op class names this hint applies to
  std::vector<ArchOverrideInfo> archOverrides;
};

/// Collect family -> SM prefix mappings from the GpuArchitecture enum.
static std::map<std::string, std::vector<std::string>>
collectFamilySmPrefixes(const RecordKeeper &records) {
  std::map<std::string, std::vector<std::string>> result;
  const Record *gpuArchEnum = findEnumByClassName(records, "GpuArchitecture");
  if (!gpuArchEnum) {
    return result;
  }
  for (const auto *c : gpuArchEnum->getValueAsListOfDefs("enumerants")) {
    std::string family = "Unknown";
    if (c->getValue("archFamily")) {
      family = c->getValueAsString("archFamily").str();
    }
    std::string str = c->getValueAsString("str").trim().str();
    result[family].push_back(str);
  }
  return result;
}

static std::vector<HintKeyInfo>
collectHintKeyInfos(const RecordKeeper &records) {
  const Record *hintKeyEnum = findEnumByClassName(records, "HintKey");
  if (!hintKeyEnum) {
    return {};
  }

  std::vector<HintKeyInfo> infos;
  for (const auto *c : hintKeyEnum->getValueAsListOfDefs("enumerants")) {
    HintKeyInfo info;
    info.sym = c->getValueAsString("symbol").str();
    info.str = c->getValueAsString("str").trim().str();
    info.retType = c->getValue("hintReturnType")
                       ? c->getValueAsString("hintReturnType").str()
                       : "int";
    info.validKind = c->getValue("hintValidationKind")
                         ? c->getValueAsString("hintValidationKind").str()
                         : "int_range";
    if (c->getValue("hintValidMin")) {
      info.validMin = c->getValueAsInt("hintValidMin");
    }
    if (c->getValue("hintValidMax")) {
      info.validMax = c->getValueAsInt("hintValidMax");
    }
    if (c->getValue("hintValidForOps")) {
      for (auto s : c->getValueAsListOfStrings("hintValidForOps")) {
        info.validForOps.push_back(s.str());
      }
    }
    if (c->getValue("hintArchOverrides")) {
      for (const auto *ovr : c->getValueAsListOfDefs("hintArchOverrides")) {
        ArchOverrideInfo aoi;
        for (auto f : ovr->getValueAsListOfStrings("archFamilies")) {
          aoi.families.push_back(f.str());
        }
        aoi.min = ovr->getValueAsInt("overrideMin");
        aoi.max = ovr->getValueAsInt("overrideMax");
        info.archOverrides.push_back(std::move(aoi));
      }
    }
    infos.push_back(std::move(info));
  }
  return infos;
}

static bool genHintKeyImpl(const RecordKeeper &records, raw_ostream &os) {
  auto infos = collectHintKeyInfos(records);
  if (infos.empty()) {
    os << "// ERROR: CudaTile_HintKey enum not found or empty.\n";
    return true;
  }

  auto familyPrefixes = collectFamilySmPrefixes(records);

  os << R"(// Auto-generated by cuda-tile-tblgen -gen-hint-key-impl.
// Do not edit.
//
// This file is #included in Attributes.cpp and provides:
//   1. Validator functions for all hints (int_range, pow2_range, bool, string)
//   2. verifyWithOp op-to-key mapping
// Getter definitions and verifier dispatch use template helpers
// in Attributes.cpp with HintKeyAccessors.inc.

#ifdef CUDA_TILE_HINT_VALIDATORS
// ---- Auto-generated validators ----

)";
  for (const auto &info : infos) {
    if (info.validKind == "bool") {
      os << formatv(R"(static ValidationResult<bool> validate{0}(
    Attribute attr, StringRef context) {{
  auto boolAttr = dyn_cast_or_null<BoolAttr>(attr);
  if (!boolAttr)
    return {{std::nullopt, ("boolean value expected for " + context + "." +
                           stringifyHintKey(HintKey::{0})).str()};
  return {{boolAttr.getValue(), ""};
}

)",
                    info.sym);
    } else if (info.validKind == "int_range" ||
               info.validKind == "pow2_range") {
      os << formatv(R"(static ValidationResult<int64_t> validate{0}(
    Attribute attr, StringRef context) {{
  auto intAttr = dyn_cast_or_null<IntegerAttr>(attr);
  if (!intAttr)
    return {{std::nullopt, ("integer value expected for " + context + "." +
                           stringifyHintKey(HintKey::{0})).str()};
  int64_t val = intAttr.getInt();
  int64_t lo = {1}, hi = {2};
)",
                    info.sym, info.validMin, info.validMax);

      for (const auto &ovr : info.archOverrides) {
        std::string condition;
        for (const auto &fam : ovr.families) {
          auto it = familyPrefixes.find(fam);
          if (it == familyPrefixes.end()) {
            PrintWarning("arch override references unknown family '" + fam +
                         "' in hint key '" + info.sym + "'");
            continue;
          }
          for (const auto &prefix : it->second) {
            if (!condition.empty()) {
              condition += " ||\n      ";
            }
            condition += "context.starts_with(\"" + prefix + "\")";
          }
        }
        if (condition.empty()) {
          continue;
        }
        os << "  if (" << condition << ") {\n";
        os << "    lo = " << ovr.min << "; hi = " << ovr.max << ";\n";
        os << "  }\n";
      }

      if (info.validKind == "pow2_range") {
        os << formatv(R"(  if (val <= 0 || (val & (val - 1)) != 0)
    return {{std::nullopt, ("power-of-2 expected for " + context + "." +
                           stringifyHintKey(HintKey::{0})).str()};
)",
                      info.sym);
      }

      os << formatv(R"(  if (val < lo || val > hi) {{
    int64_t clamped = std::clamp(val, lo, hi);
    return {{clamped, ("value " + Twine(val) + " clamped to " + Twine(clamped) +
                      " for " + context + "." +
                      stringifyHintKey(HintKey::{0})).str()};
  }
  return {{val, ""};
}

)",
                    info.sym);
    } else if (info.validKind == "string") {
      os << formatv(R"(static ValidationResult<std::string> validate{0}(
    Attribute attr, StringRef context) {{
  auto strAttr = dyn_cast_or_null<StringAttr>(attr);
  if (!strAttr)
    return {{std::nullopt, ("string value expected for " + context + "." +
                           stringifyHintKey(HintKey::{0})).str()};
  return {{std::string(strAttr.getValue()), ""};
}

)",
                    info.sym);
    }
  }

  os << "#endif // CUDA_TILE_HINT_VALIDATORS\n\n";

  // Getter definitions and verifier dispatch are handled by template helpers
  // in Attributes.cpp using HintKeyAccessors.inc — not generated here.

  // --- Section 2: verifyWithOp op-to-key mapping ---
  // Build a map: op name -> list of hint key stringified names
  std::map<std::string, std::vector<std::string>> opToKeys;
  for (const auto &info : infos) {
    for (const auto &opName : info.validForOps) {
      opToKeys[opName].push_back("stringifyHintKey(HintKey::" + info.sym + ")");
    }
  }

  os << R"(// ---- Auto-generated op-to-hint-key mapping ----
// Use: paste this block inside verifyWithOp to build keysValidForOperation.
// Guarded by CUDA_TILE_HINT_OP_KEYS.
#ifdef CUDA_TILE_HINT_OP_KEYS
)";
  for (const auto &[opName, keys] : opToKeys) {
    os << "    if (isa<" << opName << ">(op)) {\n";
    for (const auto &key : keys) {
      os << "      keysValidForOperation.push_back(" << key << ");\n";
    }
    os << "    }\n";
  }
  os << "#endif // CUDA_TILE_HINT_OP_KEYS\n";

  return false;
}

