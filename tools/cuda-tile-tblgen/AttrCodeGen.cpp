static const Record *findEnumByClassName(const RecordKeeper &records,
                                         StringRef className) {
  for (const Record *def : records.getDefs()) {
    if (!isCudaTileEnumDef(records, def)) {
      continue;
    }
    if (def->getValueAsString("className") == className) {
      return def;
    }
  }
  return nullptr;
}

// ---------------------------------------------------------------------------
// -gen-enum-attr-list
// ---------------------------------------------------------------------------

static bool genEnumAttrList(const RecordKeeper &records, raw_ostream &os) {
  os << "// This file is auto-generated by cuda-tile-tblgen "
        "-gen-enum-attr-list.\n";
  os << "// Do not edit.\n\n";
  os << "#ifndef CUDA_TILE_ENUM_ATTR\n";
  os << "#define CUDA_TILE_ENUM_ATTR(JsonKey, AttrType, EnumType)\n";
  os << "#endif\n\n";

  std::vector<EnumAttrInfo> infos;
  for (const Record *def : records.getDefs()) {
    if (isCudaTileEnumAttrWrapper(records, def)) {
      if (auto info = extractEnumAttrInfo(records, def)) {
        infos.push_back(*info);
      }
    }
  }

  llvm::sort(infos, [](const EnumAttrInfo &a, const EnumAttrInfo &b) {
    return a.jsonKey < b.jsonKey;
  });

  for (const auto &info : infos) {
    os << formatv("CUDA_TILE_ENUM_ATTR(\"{0}\", {1}, {2})\n", info.jsonKey,
                  info.attrClass, info.enumClass);
  }

  os << "\n#undef CUDA_TILE_ENUM_ATTR\n";
  return false;
}

// ---------------------------------------------------------------------------
// -gen-gpu-arch-def
// ---------------------------------------------------------------------------

static bool genGpuArchDef(const RecordKeeper &records, raw_ostream &os) {
  const Record *gpuArchEnum = findEnumByClassName(records, "GpuArchitecture");
  if (!gpuArchEnum) {
    os << "// ERROR: CudaTile_GpuArchitecture enum not found.\n";
    return true;
  }

  auto cases = gpuArchEnum->getValueAsListOfDefs("enumerants");
  if (cases.empty()) {
    os << "// ERROR: GpuArchitecture enum has no cases.\n";
    return true;
  }

  os << "// Each consumer #defines CUDA_TILE_GPU_ARCH(Sym, IntVal, Str)\n";
  os << "// before including this file.  Optionally define\n";
  os << "// CUDA_TILE_GPU_ARCH_FIRST for the first entry (defaults to\n";
  os << "// CUDA_TILE_GPU_ARCH) to avoid trailing-comma issues in\n";
  os << "// function argument lists.\n\n";
  os << "#ifndef CUDA_TILE_GPU_ARCH\n";
  os << "#define CUDA_TILE_GPU_ARCH(Sym, IntVal, Str)\n";
  os << "#endif\n\n";
  os << "#ifndef CUDA_TILE_GPU_ARCH_FIRST\n";
  os << "#define CUDA_TILE_GPU_ARCH_FIRST(Sym, IntVal, Str)                    "
        "         \\\n";
  os << "  CUDA_TILE_GPU_ARCH(Sym, IntVal, Str)\n";
  os << "#endif\n\n";

  for (size_t i = 0; i < cases.size(); ++i) {
    std::string str = cases[i]->getValueAsString("str").trim().str();
    int64_t val = cases[i]->getValueAsInt("value");
    bool isFirst = (i == 0);

    os << formatv("{0}({1}, {2}, \"{3}\")\n",
                  isFirst ? "CUDA_TILE_GPU_ARCH_FIRST" : "CUDA_TILE_GPU_ARCH",
                  str, val, str);
  }

  os << "\n#undef CUDA_TILE_GPU_ARCH\n";
  os << "#undef CUDA_TILE_GPU_ARCH_FIRST\n";
  return false;
}

// ---------------------------------------------------------------------------
// -gen-gpu-arch-constants
// ---------------------------------------------------------------------------

static bool genGpuArchConstants(const RecordKeeper &records, raw_ostream &os) {
  const Record *gpuArchEnum = findEnumByClassName(records, "GpuArchitecture");
  if (!gpuArchEnum) {
    os << "// ERROR: CudaTile_GpuArchitecture enum not found.\n";
    return true;
  }

  auto cases = gpuArchEnum->getValueAsListOfDefs("enumerants");

  struct ArchEntry {
    std::string str;
    int64_t val;
  };
  std::vector<std::string> familyOrder;
  std::map<std::string, std::vector<ArchEntry>> familyMap;

  for (const auto *c : cases) {
    std::string family = "Unknown";
    if (c->getValue("archFamily")) {
      family = c->getValueAsString("archFamily").str();
    }

    ArchEntry entry;
    entry.str = c->getValueAsString("str").trim().str();
    entry.val = c->getValueAsInt("value");
    if (familyMap.find(family) == familyMap.end()) {
      familyOrder.push_back(family);
    }
    familyMap[family].push_back(entry);
  }

  os << "// Auto-generated by cuda-tile-tblgen -gen-gpu-arch-constants\n";
  os << "// from CudaTile_GpuArchitecture enum in AttrDefs.td.\n";
  os << "// Do not edit.\n\n";

  for (const auto &family : familyOrder) {
    const auto &entries = familyMap[family];

    os << "static constexpr int32_t k" << family
       << "CCMin = " << entries.front().val << ";\n";

    for (const auto &e : entries) {
      os << "static constexpr int32_t k" << family << "Sm" << e.val << " = "
         << e.val << ";\n";
    }

    os << "static constexpr int32_t k" << family
       << "CCMax = " << entries.back().val << ";\n";

    os << "\n";
  }

  return false;
}

// ---------------------------------------------------------------------------
// -gen-hint-key-accessors
// ---------------------------------------------------------------------------

static bool genHintKeyAccessors(const RecordKeeper &records, raw_ostream &os) {
  const Record *hintKeyEnum = findEnumByClassName(records, "HintKey");
  if (!hintKeyEnum) {
    os << "// ERROR: CudaTile_HintKey enum not found.\n";
    return true;
  }

  os << R"(// Auto-generated by cuda-tile-tblgen -gen-hint-key-accessors.
// Do not edit.

#ifndef CUDA_TILE_HINT_KEY
#define CUDA_TILE_HINT_KEY(Name, Str, RetType, Version)
#endif

)";

  for (const auto *c : hintKeyEnum->getValueAsListOfDefs("enumerants")) {
    std::string sym = c->getValueAsString("symbol").str();
    std::string str = c->getValueAsString("str").trim().str();
    std::string version = c->getValueAsString("sinceVersion").str();

    std::string retType = "int";
    if (c->getValue("hintReturnType")) {
      retType = c->getValueAsString("hintReturnType").str();
    }

    os << formatv("CUDA_TILE_HINT_KEY({0}, \"{1}\", {2}, \"{3}\")\n", sym, str,
                  retType, version);
  }

  os << "\n#undef CUDA_TILE_HINT_KEY\n";
  return false;
}

