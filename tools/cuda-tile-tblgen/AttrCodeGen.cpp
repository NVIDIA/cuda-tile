static mlir::GenRegistration genEnumAttrListReg(
    "gen-enum-attr-list",
    "Generate a .inc file with X-macro entries for each CudaTile enum "
    "attribute wrapper",
    [](const RecordKeeper &records, raw_ostream &os) {
      return genEnumAttrList(records, os);
    });

static mlir::GenRegistration genGpuArchDefReg(
    "gen-gpu-arch-def",
    "Generate a .def-style .inc file with X-macro entries for each GPU "
    "architecture (consumed by C/C++ assembler headers)",
    [](const RecordKeeper &records, raw_ostream &os) {
      return genGpuArchDef(records, os);
    });

static mlir::GenRegistration genGpuArchConstantsReg(
    "gen-gpu-arch-constants",
    "Generate a .inc file with per-family SM constants and CC ranges ",
    [](const RecordKeeper &records, raw_ostream &os) {
      return genGpuArchConstants(records, os);
    });

static mlir::GenRegistration genHintKeyAccessorsReg(
    "gen-hint-key-accessors",
    "Generate a .inc file with X-macro entries for each optimization hint key "
    "(accessors for OptimizationHintsAttr)",
    [](const RecordKeeper &records, raw_ostream &os) {
      return genHintKeyAccessors(records, os);
    });

static mlir::GenRegistration genHintKeyImplReg(
    "gen-hint-key-impl",
    "Generate a .inc file with validator functions, getter definitions, "
    "verifier dispatch, and op-to-key mapping for optimization hints",
    [](const RecordKeeper &records, raw_ostream &os) {
      return genHintKeyImpl(records, os);
    });
