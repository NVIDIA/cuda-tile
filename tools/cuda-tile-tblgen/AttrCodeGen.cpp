bool isCudaTileEnumDef(const RecordKeeper &records, const Record *rec) {
  const Record *base = records.getClass("CudaTileI32EnumAttr");
  return base && rec->isSubClassOf(base);
}

bool hasI32EnumWithCases(const Record *rec) {
  auto *enumField = rec->getValue("enum");
  if (!enumField) {
    return false;
  }
  auto *enumDef = rec->getValueAsDef("enum");
  if (!enumDef) {
    return false;
  }
  return enumDef->getValue("enumerants") != nullptr;
}

bool isCudaTileEnumAttrWrapper(const RecordKeeper &records, const Record *rec) {
  const Record *base = records.getClass("CudaTileEnumAttr");
  if (base && rec->isSubClassOf(base)) {
    return hasI32EnumWithCases(rec);
  }

  const Record *enumAttr = records.getClass("EnumAttr");
  if (!enumAttr || !rec->isSubClassOf(enumAttr)) {
    return false;
  }
  auto *dialect = rec->getValueAsDef("dialect");
  if (!dialect || dialect->getName() != "CudaTile_Dialect") {
    return false;
  }
  return hasI32EnumWithCases(rec);
}

std::vector<std::pair<std::string, std::string>>
getEnumCases(const Record *enumDef) {
  std::vector<std::pair<std::string, std::string>> cases;
  for (const auto *c : enumDef->getValueAsListOfDefs("enumerants")) {
    std::string str = c->getValueAsString("str").trim().str();
    std::string sym = c->getValueAsString("symbol").str();
    cases.emplace_back(std::move(str), std::move(sym));
  }
  return cases;
}

std::optional<EnumAttrInfo> extractEnumAttrInfo(const RecordKeeper &records,
                                                const Record *wrapperRec) {
  const Record *enumInfo = wrapperRec->getValueAsDef("enum");
  if (!enumInfo) {
    return std::nullopt;
  }

  EnumAttrInfo info;
  info.enumDef = enumInfo;
  info.enumClass = enumInfo->getValueAsString("className").str();
  info.attrClass = info.enumClass + "Attr";
  info.jsonKey = wrapperRec->getValueAsString("mnemonic").str();
  return info;
}

